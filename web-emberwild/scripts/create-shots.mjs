/** Screenshot the character creation screen. usage: node create-shots.mjs <url> */
import { mkdirSync } from "node:fs";
const { chromium } = await import(process.env.RORK_PLAYWRIGHT_MODULE ?? "/usr/local/lib/node_modules/playwright/index.mjs");
const url = process.argv[2];
const out = "/tmp/perf-probe";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
await page.goto(url, { waitUntil: "networkidle", timeout: 60000 });
await page.getByRole("button", { name: /New Journey/i }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/create-top.png` });
await page.mouse.wheel(0, 800);
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/create-mid.png` });
await page.mouse.wheel(0, 900);
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/create-bot.png` });
await browser.close();
console.log("done");
